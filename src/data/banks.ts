// Helper: Filter banks worldwide by search query and region
export function searchWorldwideBanks(query: string, region: 'ALL' | 'US' | 'UK' | 'EU' | 'GLOBAL' = 'ALL'): BankOption[] {
  const cleanQ = query.trim().toLowerCase();

  return EMBEDDED_BANKS.filter(bank => {
    // Region match
    if (region !== 'ALL' && bank.region !== region) {
      return false;
    }

    if (!cleanQ) return true;

    // Search query match across Name, Country, SWIFT/BIC, Routing/Sort Code, and Logo Text
    return (
      bank.name.toLowerCase().includes(cleanQ) ||
      bank.country.toLowerCase().includes(cleanQ) ||
      bank.countryCode.toLowerCase().includes(cleanQ) ||
      (bank.swiftBic && bank.swiftBic.toLowerCase().includes(cleanQ)) ||
      (bank.code && bank.code.toLowerCase().includes(cleanQ)) ||
      bank.logoText.toLowerCase().includes(cleanQ)
    );
  });
}
